const SCALE_CACHE = {};

function getScale(scaleId) {
  if (!SCALE_META[scaleId]) return null;
  if (!SCALE_CACHE[scaleId]) {
    SCALE_CACHE[scaleId] = {
      ...SCALE_META[scaleId],
      items: buildItems(
        scaleId,
        SCALE_META[scaleId].itemCount,
        scaleId === "ipip-neo-60-zh-local-v1" ? IPIP_NEO_60_SELECTION : null
      ),
    };
  }
  return SCALE_CACHE[scaleId];
}

function listScales() {
  return Object.keys(SCALE_META).map((id) => ({ ...SCALE_META[id] }));
}

