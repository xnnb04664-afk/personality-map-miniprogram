  N1: [0, 3], N2: [0, 2], N3: [0, 1], N4: [0, 4], N5: [1, 3], N6: [3, 9],
  E1: [0, 5], E2: [0, 3], E3: [0, 1], E4: [0, 1], E5: [0, 1], E6: [1, 2],
