const FACET_ORDER = [];
for (let number = 1; number <= 6; number += 1) {
  ["N", "E", "O", "A", "C"].forEach((domain) => {
    FACET_ORDER.push(FACETS.find((item) => item.domain === domain && item.number === number));
  });
}

// Maples-Keller et al. (2019) IPIP-NEO-60 每个分面选取的题项索引。
